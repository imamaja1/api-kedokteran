<?php

namespace App\Http\Controllers\Admin;

use App\Http\Controllers\Controller;
use App\Models\ApiEndpoint;
use App\Models\ApiEndpointParameter;
use App\Models\ApiSection;
use App\Models\ApiWorkflow;
use Carbon\Carbon;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Symfony\Component\HttpFoundation\StreamedResponse;

class BackupController extends Controller
{
    /**
     * Tampilan utama menu Backup & Restore
     */
    public function index()
    {
        $dbName = DB::getDatabaseName();
        $tables = $this->getTables();
        $tableCount = count($tables);

        $rowCount = 0;
        foreach ($tables as $tableName) {
            $rowCount += DB::table($tableName)->count();
        }

        $docsStats = [
            'sections'   => ApiSection::count(),
            'endpoints'  => ApiEndpoint::count(),
            'parameters' => ApiEndpointParameter::count(),
            'workflows'  => ApiWorkflow::count(),
        ];

        return view('admin.backup.index', compact('dbName', 'tableCount', 'rowCount', 'docsStats'));
    }

    /**
     * Export / Download Database (.sql)
     */
    public function exportDb(): StreamedResponse
    {
        $driver = DB::connection()->getDriverName();
        $dbName = DB::getDatabaseName();
        $tables = $this->getTables();
        $pdo = DB::connection()->getPdo();

        $filename = 'backup_db_' . $dbName . '_' . date('Y-m-d_H-i-s') . '.sql';

        return response()->streamDownload(function () use ($tables, $pdo, $dbName, $driver) {
            echo "-- ========================================================\n";
            echo "-- Backup Database: {$dbName}\n";
            echo "-- Driver: {$driver}\n";
            echo "-- Sistem: API SISKA SIAKAD Kedokteran\n";
            echo "-- Exported At: " . now()->toIso8601String() . "\n";
            echo "-- Generated by: Admin Backup Module\n";
            echo "-- ========================================================\n\n";

            if ($driver === 'sqlite') {
                echo "PRAGMA foreign_keys = OFF;\n\n";
            } else {
                echo "SET FOREIGN_KEY_CHECKS=0;\n";
                echo "SET SQL_MODE = \"NO_AUTO_VALUE_ON_ZERO\";\n";
                echo "SET time_zone = \"+00:00\";\n\n";
            }

            foreach ($tables as $table) {
                echo "-- --------------------------------------------------------\n";
                echo "-- Struktur dari tabel `{$table}`\n";
                echo "-- --------------------------------------------------------\n";
                echo "DROP TABLE IF EXISTS `{$table}`;\n";

                if ($driver === 'sqlite') {
                    $createRes = DB::select("SELECT sql FROM sqlite_master WHERE type='table' AND name = ?", [$table]);
                    $createSql = $createRes[0]->sql ?? '';
                } else {
                    $createResult = DB::select("SHOW CREATE TABLE `{$table}`");
                    $createSql = $createResult[0]->{'Create Table'} ?? '';
                }
                echo $createSql . ";\n\n";

                $rows = DB::table($table)->get();
                if ($rows->isNotEmpty()) {
                    echo "-- Dumping data untuk tabel `{$table}` (" . $rows->count() . " records)\n";
                    $columns = array_keys((array) $rows->first());
                    $escapedColumns = array_map(fn($col) => "`{$col}`", $columns);
                    $columnList = implode(', ', $escapedColumns);

                    foreach ($rows->chunk(100) as $chunk) {
                        $valuesList = [];
                        foreach ($chunk as $row) {
                            $rowValues = [];
                            foreach ($columns as $col) {
                                $val = $row->$col;
                                if ($val === null) {
                                    $rowValues[] = 'NULL';
                                } elseif (is_numeric($val) && ! is_string($val)) {
                                    $rowValues[] = $val;
                                } else {
                                    $rowValues[] = $pdo->quote((string) $val);
                                }
                            }
                            $valuesList[] = '(' . implode(', ', $rowValues) . ')';
                        }
                        echo "INSERT INTO `{$table}` ({$columnList}) VALUES\n" . implode(",\n", $valuesList) . ";\n";
                    }
                    echo "\n";
                }
            }

            if ($driver === 'sqlite') {
                echo "PRAGMA foreign_keys = ON;\n";
            } else {
                echo "SET FOREIGN_KEY_CHECKS=1;\n";
            }
            echo "-- [SELESAI BACKUP DATABASE]\n";
        }, $filename, [
            'Content-Type'        => 'application/sql',
            'Content-Disposition' => "attachment; filename=\"{$filename}\"",
        ]);
    }

    /**
     * Import / Restore Database dari file .sql
     */
    public function importDb(Request $request)
    {
        $request->validate([
            'sql_file' => 'required|file|max:102400', // Max 100MB
        ]);

        $file = $request->file('sql_file');
        $ext = strtolower($file->getClientOriginalExtension());
        if (! in_array($ext, ['sql', 'txt'], true)) {
            return redirect()->route('admin.backup.index')->with('error', 'Format file tidak didukung. Harap unggah file berekstensi .sql');
        }

        try {
            $sqlContent = file_get_contents($file->getRealPath());

            $this->disableForeignKeys();
            DB::unprepared($sqlContent);
            $this->enableForeignKeys();

            return redirect()->route('admin.backup.index')->with('success', 'Database berhasil dipulihkan dari file backup (' . $file->getClientOriginalName() . ').');
        } catch (\Throwable $e) {
            $this->enableForeignKeys();
            return redirect()->route('admin.backup.index')->with('error', 'Gagal memulihkan database: ' . $e->getMessage());
        }
    }

    /**
     * Export / Download Dokumentasi API (.json)
     */
    public function exportDocs(): StreamedResponse
    {
        $sections = ApiSection::orderBy('sort_order')->get();
        $endpoints = ApiEndpoint::orderBy('sort_order')->get();
        $parameters = ApiEndpointParameter::orderBy('sort_order')->get();
        $workflows = ApiWorkflow::orderBy('sort_order')->get();

        $payload = [
            'app'         => 'API SISKA KEDOKTERAN',
            'export_type' => 'api_documentation',
            'exported_at' => now()->toIso8601String(),
            'version'     => '1.0',
            'summary'     => [
                'total_sections'   => $sections->count(),
                'total_endpoints'  => $endpoints->count(),
                'total_parameters' => $parameters->count(),
                'total_workflows'  => $workflows->count(),
            ],
            'api_sections'            => $sections,
            'api_endpoints'           => $endpoints,
            'api_endpoint_parameters' => $parameters,
            'api_workflows'           => $workflows,
        ];

        $json = json_encode($payload, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        $filename = 'backup_dokumentasi_api_' . date('Y-m-d_H-i-s') . '.json';

        return response()->streamDownload(function () use ($json) {
            echo $json;
        }, $filename, [
            'Content-Type'        => 'application/json',
            'Content-Disposition' => "attachment; filename=\"{$filename}\"",
        ]);
    }

    /**
     * Import / Restore Dokumentasi API dari file .json
     * Melakukan Truncate bersih pada tabel dokumentasi lama lalu memasukkan data baru
     */
    public function importDocs(Request $request)
    {
        $request->validate([
            'json_file' => 'required|file|max:20480', // Max 20MB
        ]);

        $file = $request->file('json_file');
        $ext = strtolower($file->getClientOriginalExtension());
        if (! in_array($ext, ['json', 'txt'], true)) {
            return redirect()->route('admin.backup.index')->with('error', 'Format file tidak didukung. Harap unggah file berekstensi .json');
        }

        $content = file_get_contents($file->getRealPath());
        $data = json_decode($content, true);

        if (! is_array($data)) {
            return redirect()->route('admin.backup.index')->with('error', 'File JSON tidak valid atau rusak.');
        }

        try {
            $this->disableForeignKeys();

            // Truncate tabel dokumentasi lama secara berurutan
            $this->truncateTable('api_endpoint_parameters');
            $this->truncateTable('api_endpoints');
            $this->truncateTable('api_sections');
            $this->truncateTable('api_workflows');

            // 1. Insert Sections
            $sections = $data['api_sections'] ?? $data['sections'] ?? [];
            if (! empty($sections)) {
                $sectionInserts = [];
                foreach ($sections as $s) {
                    $sectionInserts[] = [
                        'id'         => $s['id'],
                        'title'      => $s['title'],
                        'sort_order' => $s['sort_order'] ?? 0,
                        'created_at' => $this->parseDateTime($s['created_at'] ?? null),
                        'updated_at' => $this->parseDateTime($s['updated_at'] ?? null),
                    ];
                }
                foreach (array_chunk($sectionInserts, 100) as $chunk) {
                    DB::table('api_sections')->insert($chunk);
                }
            }

            // 2. Insert Endpoints
            $endpoints = $data['api_endpoints'] ?? $data['endpoints'] ?? [];
            if (! empty($endpoints)) {
                $endpointInserts = [];
                foreach ($endpoints as $ep) {
                    $endpointInserts[] = [
                        'id'               => $ep['id'],
                        'api_section_id'   => $ep['api_section_id'],
                        'title'            => $ep['title'],
                        'description'      => $ep['description'] ?? null,
                        'method'           => $ep['method'],
                        'url'              => $ep['url'],
                        'headers'          => $ep['headers'] ?? null,
                        'body'             => $ep['body'] ?? null,
                        'response_example' => $ep['response_example'] ?? null,
                        'sort_order'       => $ep['sort_order'] ?? 0,
                        'created_at'       => $this->parseDateTime($ep['created_at'] ?? null),
                        'updated_at'       => $this->parseDateTime($ep['updated_at'] ?? null),
                    ];
                }
                foreach (array_chunk($endpointInserts, 100) as $chunk) {
                    DB::table('api_endpoints')->insert($chunk);
                }
            }

            // 3. Insert Parameters
            $parameters = $data['api_endpoint_parameters'] ?? $data['parameters'] ?? [];
            if (! empty($parameters)) {
                $paramInserts = [];
                foreach ($parameters as $p) {
                    $paramInserts[] = [
                        'id'                 => $p['id'],
                        'api_endpoint_id'    => $p['api_endpoint_id'],
                        'name'               => $p['name'],
                        'type'               => $p['type'] ?? 'string',
                        'location'           => $p['location'] ?? 'query',
                        'is_required'        => (bool) ($p['is_required'] ?? false),
                        'source_type'        => $p['source_type'] ?? 'input',
                        'source_endpoint_id' => $p['source_endpoint_id'] ?? null,
                        'source_field'       => $p['source_field'] ?? null,
                        'source_note'        => $p['source_note'] ?? null,
                        'example'            => $p['example'] ?? null,
                        'sort_order'         => $p['sort_order'] ?? 0,
                        'created_at'         => $this->parseDateTime($p['created_at'] ?? null),
                        'updated_at'         => $this->parseDateTime($p['updated_at'] ?? null),
                    ];
                }
                foreach (array_chunk($paramInserts, 100) as $chunk) {
                    DB::table('api_endpoint_parameters')->insert($chunk);
                }
            }

            // 4. Insert Workflows
            $workflows = $data['api_workflows'] ?? $data['workflows'] ?? [];
            if (! empty($workflows)) {
                $workflowInserts = [];
                foreach ($workflows as $wf) {
                    $workflowInserts[] = [
                        'id'         => $wf['id'],
                        'title'      => $wf['title'],
                        'badge'      => $wf['badge'] ?? null,
                        'icon'       => $wf['icon'] ?? 'route',
                        'summary'    => $wf['summary'] ?? '',
                        'roles'      => is_array($wf['roles']) ? json_encode($wf['roles']) : ($wf['roles'] ?? '[]'),
                        'rules'      => is_array($wf['rules']) ? json_encode($wf['rules']) : ($wf['rules'] ?? '{}'),
                        'phases'     => is_array($wf['phases']) ? json_encode($wf['phases']) : ($wf['phases'] ?? '[]'),
                        'sort_order' => $wf['sort_order'] ?? 0,
                        'is_active'  => (bool) ($wf['is_active'] ?? true),
                        'created_at' => $this->parseDateTime($wf['created_at'] ?? null),
                        'updated_at' => $this->parseDateTime($wf['updated_at'] ?? null),
                    ];
                }
                foreach (array_chunk($workflowInserts, 50) as $chunk) {
                    DB::table('api_workflows')->insert($chunk);
                }
            }

            $this->enableForeignKeys();

            $secCount = count($sections);
            $epCount = count($endpoints);
            $paramCount = count($parameters);
            $wfCount = count($workflows);

            return redirect()->route('admin.backup.index')->with('success', "Dokumentasi API berhasil dipulihkan secara bersih (Truncate & Insert)! Berhasil memasukkan {$secCount} Seksi, {$epCount} Endpoint, {$paramCount} Parameter, dan {$wfCount} Workflow.");
        } catch (\Throwable $e) {
            $this->enableForeignKeys();
            return redirect()->route('admin.backup.index')->with('error', 'Gagal mengimpor dokumentasi: ' . $e->getMessage());
        }
    }

    /**
     * Parse string datetime menjadi format MySQL yang valid (Y-m-d H:i:s)
     * Mengatasi format ISO 8601 seperti '2026-09-22T14:27:46.000000Z'
     */
    private function parseDateTime(mixed $date): string
    {
        if (empty($date)) {
            return now()->format('Y-m-d H:i:s');
        }

        try {
            return Carbon::parse($date)->format('Y-m-d H:i:s');
        } catch (\Throwable) {
            return now()->format('Y-m-d H:i:s');
        }
    }

    /**
     * Dapatkan daftar nama tabel sesuai database driver yang aktif
     */
    private function getTables(): array
    {
        $driver = DB::connection()->getDriverName();
        if ($driver === 'sqlite') {
            $rows = DB::select("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'");
            return array_map(fn($r) => $r->name, $rows);
        }

        $dbName = DB::getDatabaseName();
        $tables = DB::select('SHOW TABLES');
        $prop = 'Tables_in_' . $dbName;
        return array_map(fn($t) => $t->$prop, $tables);
    }

    /**
     * Kosongkan tabel secara kompatibel (MySQL TRUNCATE / SQLite DELETE)
     */
    private function truncateTable(string $table): void
    {
        if (DB::connection()->getDriverName() === 'sqlite') {
            DB::table($table)->delete();
        } else {
            DB::statement("TRUNCATE TABLE `{$table}`");
        }
    }

    private function disableForeignKeys(): void
    {
        if (DB::connection()->getDriverName() === 'sqlite') {
            DB::statement('PRAGMA foreign_keys = OFF;');
        } else {
            DB::statement('SET FOREIGN_KEY_CHECKS=0;');
        }
    }

    private function enableForeignKeys(): void
    {
        if (DB::connection()->getDriverName() === 'sqlite') {
            DB::statement('PRAGMA foreign_keys = ON;');
        } else {
            DB::statement('SET FOREIGN_KEY_CHECKS=1;');
        }
    }
}
